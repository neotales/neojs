#!/usr/bin/env python3
"""Generate `src/strings/case_fold.rs` from the pinned Unicode 16.0 artifact.

The input is the exact official Unicode Character Database file:
https://www.unicode.org/Public/16.0.0/ucd/CaseFolding.txt

The script refuses to run unless the artifact's SHA-256 matches the pinned
value and its version header is the expected release. It selects status `C`
and `S` entries only: those are the simple case-folding mappings. `F` (full)
and `T` (Turkic) entries are intentionally ignored.

Usage:
    python3 scripts/generate_case_fold.py
    python3 scripts/generate_case_fold.py --check

`--check` exits nonzero when the committed file is not exactly what the pinned
artifact generates. It does not need a display or any network access.
"""

from __future__ import annotations

import difflib
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ARTIFACT = ROOT / "data" / "unicode" / "CaseFolding-16.0.0.txt"
TARGET = ROOT / "src" / "strings" / "case_fold.rs"

SOURCE_URL = "https://www.unicode.org/Public/16.0.0/ucd/CaseFolding.txt"
SOURCE_SHA256 = "6f1f9c588eb4a5c718d9e8f93b782685e5c7fec872cf05e8e6878053599e09bb"
EXPECTED_HEADER = "# CaseFolding-16.0.0.txt"


def verify_artifact() -> None:
    data = ARTIFACT.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SOURCE_SHA256:
        raise SystemExit(
            f"{ARTIFACT} SHA-256 is {digest}, expected {SOURCE_SHA256}"
        )
    first = data.decode("utf-8").splitlines()[0]
    if first != EXPECTED_HEADER:
        raise SystemExit(f"{ARTIFACT} starts with {first!r}, expected {EXPECTED_HEADER!r}")


def simple_mappings() -> dict[int, int]:
    mappings: dict[int, int] = {}
    for line_number, line in enumerate(
        ARTIFACT.read_text(encoding="utf-8").splitlines(), 1
    ):
        payload = line.split("#", 1)[0].strip()
        if not payload:
            continue
        fields = [field.strip() for field in payload.split(";")]
        if len(fields) < 3 or any(fields[3:]):
            raise SystemExit(f"line {line_number}: expected three fields")
        code = int(fields[0], 16)
        status = fields[1]
        mapping = fields[2].split()
        if status not in ("C", "S"):
            continue
        if len(mapping) != 1:
            raise SystemExit(f"line {line_number}: simple mapping is not one code point")
        target = int(mapping[0], 16)
        previous = mappings.get(code)
        if previous is not None and previous != target:
            raise SystemExit(f"line {line_number}: conflicting simple mappings")
        mappings[code] = target
    return mappings


def ranges(mappings: dict[int, int]) -> list[tuple[int, int, int]]:
    merged: list[list[int]] = []
    for code, target in sorted(mappings.items()):
        if (
            merged
            and merged[-1][1] + 1 == code
            and merged[-1][2] + (merged[-1][1] - merged[-1][0]) + 1 == target
        ):
            merged[-1][1] = code
        else:
            merged.append([code, code, target])
    return [(start, end, target) for start, end, target in merged]


def render(merged: list[tuple[int, int, int]]) -> str:
    lines = [
        "//! Unicode simple case-folding table for `vael:strings`.",
        "//!",
        "//! Generated by `scripts/generate_case_fold.py` from the pinned Unicode",
        "//! 16.0 `CaseFolding.txt` artifact. Do not edit by hand.",
        "//!",
        f"//! Source: {SOURCE_URL}",
        f"//! Artifact SHA-256: {SOURCE_SHA256}",
        "//! License: Unicode License V3; see `data/UNICODE-LICENSE.txt`.",
        "//! Selection: status `C` and `S` entries, one target code point each;",
        "//! `F` and `T` entries are ignored. Ranges merge only when both the",
        "//! source and target code points are consecutive.",
        "//!",
        "//! Unicode 16.0 is the release this V8 build's `/iu` canonicalization",
        "//! follows: the engine rejects a fold between code points added in",
        "//! Unicode 17.0, and the `vael:chars` tables are pinned to the same",
        "//! release. Entries whose full case folding expands to more than one",
        "//! code point keep their one-code-point simple mapping (for example",
        "//! U+1E9E folds to U+00DF) or are identity when Unicode defines no",
        "//! simple mapping (for example U+00DF). Code points unassigned in",
        "//! Unicode 16.0 are identity.",
        "//!",
        "//! `simple_fold` is an idempotent function on Unicode scalar values and",
        "//! on the lone surrogate code units that a JavaScript string can contain.",
        "//! Comparing the folded code points is the same equivalence the previous",
        "//! ECMAScript implementation obtained from the engine's `/iu`",
        "//! canonicalization for the cases this module documents.",
        "",
        "/// The simple case-folding ranges, sorted by inclusive start.",
        "pub(crate) const RANGES: &[(u32, u32, u32)] = &[",
    ]
    for start, end, target in merged:
        lines.append(f"    (0x{start:04X}, 0x{end:04X}, 0x{target:04X}),")
    lines.extend(
        [
            "];",
            "",
            "/// Returns the Unicode simple case folding of `point`.",
            "///",
            "/// A code point outside the table, including a lone surrogate code unit,",
            "/// folds to itself. The lookup is a binary search over the range starts,",
            f"/// so it is `O(log n)` with a {len(merged)}-entry table.",
            "#[must_use]",
            "pub(crate) fn simple_fold(point: u32) -> u32 {",
            "    if point < 0x80 {",
            "        return if (b'A' as u32..=b'Z' as u32).contains(&point) {",
            "            point + 0x20",
            "        } else {",
            "            point",
            "        };",
            "    }",
            "    let index = RANGES.partition_point(|&(start, _, _)| start <= point);",
            "    if index == 0 {",
            "        return point;",
            "    }",
            "    let (start, end, target) = RANGES[index - 1];",
            "    if point <= end {",
            "        target + (point - start)",
            "    } else {",
            "        point",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    verify_artifact()
    rendered = render(ranges(simple_mappings()))
    if "--check" in sys.argv[1:]:
        current = TARGET.read_text(encoding="utf-8")
        if current == rendered:
            print(f"{TARGET} is up to date")
            return 0
        diff = difflib.unified_diff(
            current.splitlines(),
            rendered.splitlines(),
            fromfile=str(TARGET),
            tofile="generated",
            lineterm="",
        )
        print("\n".join(diff))
        return 1
    TARGET.write_text(rendered, encoding="utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
